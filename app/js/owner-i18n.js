export function ownerText(lang, key, vars) {
  const dict = OWNER_I18N[lang] || OWNER_I18N.ko;
  let value = dict[key];
  if (value === undefined) value = OWNER_I18N.en[key];
  if (value === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      value = value.split('{' + name + '}').join(vars[name] == null ? '' : String(vars[name]));
    });
  }
  return value;
}
